def _table(fam: str, guide: dict) -> str:
    verbs = by_family(guide).get(fam) or []
    lines = [
        BEGIN,
        "",
        f"## Every {FAMILIES[fam].title.lower()} verb",
        "",
        (
            "Shown as `aurora <verb>`; in a checkout without the installed launcher run "
            "`uv run agent_cli.py <verb>`. `<you>` is your agent id. `--help` on any verb gives every flag."
        ),
        "",
        "| Verb | Use when | Example |",
        "|---|---|---|",
    ]
    for v in verbs:
        when = guide[v].get("when", "").removeprefix("Use when ").replace("|", "\\|")
        ex = command(v, "aurora", guide=guide).replace("|", "\\|")
        lines.append(f"| `{v}` | {when} | `{ex}` |")
    lines += ["", END]
    return "\n".join(lines) + "\n"


def _new_skill(fam: str, table: str) -> str:
    f = FAMILIES[fam]
    head = f"---\nname: {f.skill}\ndescription: {DESCRIPTIONS[fam]}\n---\n\n"
    title = f"# {f.title}: {f.situation}\n\n"
    intro = (
        "These are your tools for this situation in the Akashic Aurora house. Reach for them by "
        "default, before hand-rolled shell; the hooks will point at a verb when a command you are "
        "about to run does its job by hand.\n\n"
    )
    return head + title + intro + PLAYBOOKS[fam] + "\n" + table


def render(fam: str, existing: str | None, guide: dict) -> str:
    table = _table(fam, guide)
    if existing is None:
        return _new_skill(fam, table)
    if BEGIN in existing and END in existing:
        pre, rest = existing.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        return pre + table.rstrip("\n") + post
    return existing.rstrip("\n") + "\n\n" + table


def targets() -> list[tuple[str, str]]:
    return [(fam, os.path.join(SKILLS_DIR, f.skill, "SKILL.md")) for fam, f in FAMILIES.items()]


def main() -> int:
    guide = load()
    check = "--check" in sys.argv
    stale = []
    for fam, path in targets():
        existing = Path(path).read_text(encoding="utf-8") if os.path.exists(path) else None
        want = render(fam, existing, guide)
        if want == existing:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(want)
        print(f"wrote {os.path.relpath(path, ROOT)}")
    if stale:
        print("stale verb tables (run scripts/generators/gen_verb_skills.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
