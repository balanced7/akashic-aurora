"""gen_verb_skills -- the family skills: one skill per verb family, its verb table derived.

Layer 3 of the verb guide (core/coord/verb_guide.py says why the house pushes verbs instead of
waiting to be asked). A skill's description is always in an agent's context and its body loads
when the situation arrives, which is exactly the shape a FAMILY of verbs needs: the map says a
verb exists, the skill says how a working session strings them together.

Each SKILL.md has two parts:
  * the hand-written playbook -- the usual sequences and traps. Created from PLAYBOOKS below on
    first generation, then owned by whoever edits the file: the generator never rewrites it.
  * the verb table between the markers -- derived from verb_guide.json on every run, so a verb
    added to the parser and the guide reaches its skill with no hand step.

akashic-memory predates this and is hand-written; it gets the memory family's table appended
between the same markers and nothing else.

Run:  uv run scripts/generators/gen_verb_skills.py           # writes .agents/skills/*/SKILL.md
      uv run scripts/generators/gen_verb_skills.py --check   # exit 1 if any table is stale
"""

