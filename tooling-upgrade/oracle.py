    hit = any(k == "name:{}.{}".format(picked["mod"], picked["fn"]) for k, _ in diffs)
    print("D14 SELF-TEST: %s" % ("O5 DIFF DETECTED" if hit else "MISSED"))
    return 0 if hit else 1


