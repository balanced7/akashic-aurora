def impacted(commit: str) -> list:
    changed = git("diff", "--name-only", commit + "^", commit, "--", "*.py").splitlines()
    pys = [f for f in tracked_files() if f.endswith(".py")]
    graph = RepoGraph(ROOT, pys)
    rev = graph.reverse()
    seen, stack = set(), [c for c in changed if c in graph.asts]
    while stack:
        f = stack.pop()
        if f in seen:
            continue
        seen.add(f)
        stack.extend(rev.get(f, ()))
    tests = {f for f in seen if f.startswith("tests/") and f.rsplit("/", 1)[-1].startswith("test")}
    tests |= {t for t in SMOKE_TESTS if (ROOT / t).exists()}
    return sorted(tests)


def cmd_impacted(args) -> int:
    for t in impacted(args.commit):
        print(t)
    return 0


