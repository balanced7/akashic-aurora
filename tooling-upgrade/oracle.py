def surface_o6(tree: Path, raw: Path) -> dict:
    out = {}
    for p in sorted((tree / "scripts" / "checkers").glob("*.py")):
        if p.name.startswith("_"):
            continue
        progress("O6 %s" % p.stem)
        try:
            r = run([venv_python(tree), p.relative_to(tree).as_posix()], cwd=tree,
                    env=oracle_env(), timeout=CHECKER_TIMEOUT_S)
            text = normalize_text(r.stdout + r.stderr, tree)
            item = {"rc": r.returncode, "crashed": "Traceback (most recent call last)" in text,
                    "lines": len(text.splitlines()), "digest": sha256_bytes(text.encode())}
            if r.returncode == 2 and "usage:" in text and "required" in text:
                item["na"] = "needs arguments"
            (raw / ("O6-%s.log" % p.stem)).write_text(text, encoding="utf-8")
        except subprocess.TimeoutExpired:
            item = {"rc": 999, "crashed": True, "lines": 0, "digest": "", "na": "timeout"}
        out[p.stem] = item
    return {"checkers": out}


def compare_o6(a, b, partial=False) -> list:
    diffs = []
    for name, r in sorted(a["checkers"].items()):
        rb = b["checkers"].get(name)
        if rb is None:
            diffs.append(("checker:" + name, "checker gone"))
            continue
        if rb["crashed"] and not r["crashed"]:
            diffs.append(("checker:" + name, "now crashes"))
        elif rb["rc"] > r["rc"]:
            diffs.append(("checker:" + name, "exit %d > baseline %d" % (rb["rc"], r["rc"])))
    return diffs


