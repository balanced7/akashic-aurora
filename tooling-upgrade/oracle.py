# ----------------------------------------------------------------------------- O9 test strength

def assertion_count(fn) -> int:
    n = 0
    for node in ast.walk(fn):
        if isinstance(node, ast.Assert):
            n += 1
        elif isinstance(node, (ast.With, ast.AsyncWith)):
            for item in node.items:
                c = item.context_expr
                if isinstance(c, ast.Call):
                    name = ast.unparse(c.func)
                    if name.endswith(("raises", "warns", "deprecated_call")):
                        n += 1
        elif isinstance(node, ast.Call):
            name = ast.unparse(node.func)
            last = name.rsplit(".", 1)[-1]
            if last.startswith("assert") or name in ("pytest.fail", "fail"):
                n += 1
    return n


def test_strength(tree_root: Path, files=None) -> dict:
    files = files or [f for f in tracked_files(tree_root) if f.startswith("tests/") and f.endswith(".py")]
    out = {}
    for f in files:
        tree = parse_file(tree_root / f)
        if tree is None:
            continue
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test"):
                out["%s::%s" % (f, node.name)] = assertion_count(node)
            elif isinstance(node, ast.ClassDef) and node.name.startswith("Test"):
                for sub in node.body:
                    if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)) and sub.name.startswith("test"):
                        out["%s::%s::%s" % (f, node.name, sub.name)] = assertion_count(sub)
    return {"tests": dict(sorted(out.items())), "total": sum(out.values())}


def compare_o9(a, b, partial=False) -> list:
    diffs = []
    for k, n in sorted(a["tests"].items()):
        nb = b["tests"].get(k)
        if nb is None:
            diffs.append(("test:" + k, "test function gone"))
        elif nb < n:
            diffs.append(("test:" + k, "assertions %d -> %d" % (n, nb)))
    if b["total"] < a["total"]:
        diffs.append(("total", "total assertions %d -> %d" % (a["total"], b["total"])))
    return diffs


