def parse_file(path: Path):
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")   # invalid escapes in archived code are not ours to fix
            return ast.parse(path.read_bytes(), filename=str(path))
    except (SyntaxError, ValueError):
        return None


def dotted_name(rel: str):
    """'core/foo/bar.py' -> 'core.foo.bar'; '__init__' collapses; None if not identifier-safe."""
    parts = rel[:-3].split("/")
    if parts[-1] == "__init__":
        parts = parts[:-1]
    if not parts or not all(p.isidentifier() for p in parts):
        return None
    return ".".join(parts)


def is_history(rel: str) -> bool:
    return rel.startswith(HISTORY_TREES)


def has_main_guard(tree) -> bool:
    for node in tree.body if tree else ():
        if isinstance(node, ast.If):
            t = ast.unparse(node.test).replace("'", '"')
            if "__name__" in t and '"__main__"' in t:
                return True
    return False


def uses_argparse(tree) -> bool:
    for node in ast.walk(tree) if tree else ():
        if isinstance(node, ast.Import) and any(a.name == "argparse" for a in node.names):
            return True
        if isinstance(node, ast.ImportFrom) and node.module == "argparse":
            return True
    return False


def import_safe(tree) -> tuple[bool, str]:
    """Can importing this module run it? A top-level call that is not a known-benign set-up call
    (sys.path, warnings, logging) means the import IS the run -- the oracle never does that."""
    if tree is None:
        return False, "unparseable"
    for node in tree.body:
        if isinstance(node, ast.Expr):
            if isinstance(node.value, ast.Constant):
                continue
            if isinstance(node.value, ast.Call):
                name = ast.unparse(node.value.func)
                if _SAFE_TOPLEVEL_CALLS.match(name):
                    continue
                return False, "top-level call %s()" % name
            if isinstance(node.value, (ast.Await, ast.Yield)):
                return False, "top-level await"
            continue
        if isinstance(node, (ast.For, ast.AsyncFor, ast.While, ast.With, ast.AsyncWith)):
            return False, "top-level %s block" % type(node).__name__
    return True, ""


def top_level_bindings(tree, include_imports=False) -> set[str]:
    """Names bound at module top level (walking into if/try/with, never into defs)."""
    names: set[str] = set()

    def targets(t):
        if isinstance(t, ast.Name):
            names.add(t.id)
        elif isinstance(t, (ast.Tuple, ast.List)):
            for e in t.elts:
                targets(e)
        elif isinstance(t, ast.Starred):
            targets(t.value)

    def visit(body):
        for node in body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                names.add(node.name)
            elif isinstance(node, ast.Assign):
                for t in node.targets:
                    targets(t)
            elif isinstance(node, (ast.AnnAssign, ast.AugAssign)):
                targets(node.target)
            elif isinstance(node, (ast.Import, ast.ImportFrom)) and include_imports:
                for a in node.names:
                    if a.name != "*":
                        names.add((a.asname or a.name).split(".")[0])
            elif isinstance(node, ast.If):
                visit(node.body)
                visit(node.orelse)
            elif isinstance(node, ast.Try) or type(node).__name__ == "TryStar":
                visit(node.body)
                for h in node.handlers:
                    visit(h.body)
                visit(node.orelse)
                visit(node.finalbody)
            elif isinstance(node, (ast.With, ast.AsyncWith)):
                visit(node.body)
    visit(tree.body if tree else [])
    return names


def static_all(tree):
    for node in tree.body if tree else ():
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            tgts = node.targets if isinstance(node, ast.Assign) else [node.target]
            if any(isinstance(t, ast.Name) and t.id == "__all__" for t in tgts):
                try:
                    return sorted(set(ast.literal_eval(node.value)))
                except Exception:
                    return None
    return None


def static_signatures(tree) -> dict:
    sigs = {}
    for node in tree.body if tree else ():
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            full = "(%s)" % ast.unparse(node.args)
            if node.returns is not None:
                full += " -> " + ast.unparse(node.returns)
            bare_args = ast.parse("def f(%s): pass" % ast.unparse(node.args)).body[0].args
            for a in bare_args.posonlyargs + bare_args.args + bare_args.kwonlyargs:
                a.annotation = None
            for a in (bare_args.vararg, bare_args.kwarg):
                if a is not None:
                    a.annotation = None
            sigs[node.name] = {"full": full, "bare": "(%s)" % ast.unparse(bare_args)}
    return sigs


ANNOTATION_TRIGGERS = {
    "get_type_hints": "typing.get_type_hints", "__annotations__": "__annotations__",
    "signature": "inspect.signature", "dataclass": "dataclass", "dataclasses": "dataclass",
    "pydantic": "pydantic", "BaseModel": "pydantic", "FastMCP": "FastMCP",
}


def annotation_triggers(tree) -> list[str]:
    found = set()
    for node in ast.walk(tree) if tree else ():
        if isinstance(node, ast.Name) and node.id in ANNOTATION_TRIGGERS:
            found.add(ANNOTATION_TRIGGERS[node.id])
        elif isinstance(node, ast.Attribute) and node.attr in ANNOTATION_TRIGGERS:
            found.add(ANNOTATION_TRIGGERS[node.attr])
        elif isinstance(node, ast.ImportFrom) and node.module:
            top = node.module.split(".")[0]
            if top in ("pydantic", "dataclasses"):
                found.add(ANNOTATION_TRIGGERS[top])
            for a in node.names:
                if a.name in ANNOTATION_TRIGGERS:
                    found.add(ANNOTATION_TRIGGERS[a.name])
        elif isinstance(node, ast.Import):
            for a in node.names:
                if a.name.split(".")[0] in ("pydantic", "dataclasses"):
                    found.add(ANNOTATION_TRIGGERS[a.name.split(".")[0]])
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for d in node.decorator_list:
                d = d.func if isinstance(d, ast.Call) else d
                if isinstance(d, ast.Attribute) and d.attr in ("tool", "resource", "prompt"):
                    found.add("@*.%s decorator" % d.attr)
    return sorted(found)


class RepoGraph:
    """Static import graph over the tracked .py files of one tree."""

    def __init__(self, tree_root: Path, files: list[str]):
        self.root = tree_root
        self.files = [f for f in files if f.endswith(".py")]
        self.asts = {f: parse_file(tree_root / f) for f in self.files}
        self.by_dotted = {}
        for f in self.files:
            d = dotted_name(f)
            if d:
                self.by_dotted.setdefault(d, f)
        self.edges = {f: set() for f in self.files}      # importer -> imported files
        self.ext_names = {}                               # file -> names others take from it
        for f in self.files:
            self._scan(f)

    def _resolve(self, importer: str, dotted: str) -> list[str]:
        hits = []
        parts = dotted.split(".")
        for i in range(1, len(parts) + 1):
            f = self.by_dotted.get(".".join(parts[:i]))
            if f:
                hits.append(f)
        # script-local import: a sibling module next to the importer (sys.path[0] is its dir)
        base = os.path.dirname(importer)
        for cand in (dotted.replace(".", "/") + ".py", dotted.replace(".", "/") + "/__init__.py"):
            rel = (base + "/" + cand) if base else cand
            if rel in self.asts:
                hits.append(rel)
        return hits

    def _scan(self, f: str) -> None:
        tree = self.asts[f]
        if tree is None:
            return
        pkg = f[:-3].split("/")[:-1]   # the importer's package (for __init__.py: its own dir)
        aliases = {}
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for a in node.names:
                    for hit in self._resolve(f, a.name):
                        self.edges[f].add(hit)
                    if a.asname:
                        aliases[a.asname] = a.name
                    else:
                        aliases[a.name.split(".")[0]] = a.name.split(".")[0]
                        aliases[a.name] = a.name
            elif isinstance(node, ast.ImportFrom):
                if node.level:
                    base = pkg[: len(pkg) - (node.level - 1)] if node.level > 1 else pkg
                    mod = ".".join(base + ([node.module] if node.module else []))
                else:
                    mod = node.module or ""
                targets = self._resolve(f, mod) if mod else []
                for hit in targets:
                    self.edges[f].add(hit)
                for a in node.names:
                    sub = self._resolve(f, mod + "." + a.name if mod else a.name)
                    sub = [s for s in sub if s not in targets]
                    if sub:
                        self.edges[f].update(sub)
                    elif targets and a.name != "*":
                        self.ext_names.setdefault(targets[-1], set()).add(a.name)
            elif isinstance(node, ast.Call):
                fn = ast.unparse(node.func)
                if (fn.endswith(("import_module", "__import__", "run_module"))
                        and node.args and isinstance(node.args[0], ast.Constant)
                        and isinstance(node.args[0].value, str)):
                    for hit in self._resolve(f, node.args[0].value):
                        self.edges[f].add(hit)
        for node in ast.walk(tree):
            if isinstance(node, ast.Attribute) and isinstance(node.value, (ast.Name, ast.Attribute)):
                owner = ast.unparse(node.value)
                if owner in aliases:
                    hits = self._resolve(f, aliases[owner])
                    if hits and not node.attr.startswith("_"):
                        self.ext_names.setdefault(hits[-1], set()).add(node.attr)

    def reverse(self) -> dict:
        rev = {f: set() for f in self.files}
        for src, dsts in self.edges.items():
            for d in dsts:
                rev.setdefault(d, set()).add(src)
        return rev


