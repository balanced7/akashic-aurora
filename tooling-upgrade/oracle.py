def oracle_env(extra=None) -> dict:
    """The one environment every probe runs in: the caller's, scrubbed of anything that would
    make a run depend on who launched it, plus REDIS_DB=15 and a fixed terminal size."""
    env = {k: v for k, v in os.environ.items()
           if not (k.startswith(("PYTHON", "REDIS_", "AKASHIC_", "UV_", "PYTEST", "COV_"))
                   or k in ("VIRTUAL_ENV", "COLUMNS", "LINES", "CONDA_PREFIX"))}
    env.update({"REDIS_DB": "15", "COLUMNS": "80", "LINES": "24"})
    env.update(extra or {})
    return env


def normalize_text(s: str, tree: Path | None = None) -> str:
    """Whitespace-normalised, path-neutral text: what O4/O6/O7 compare."""
    for root in filter(None, (tree, ROOT)):
        for form in {str(root), Path(root).as_posix()}:
            s = s.replace(form, "<ROOT>")
    home = str(Path.home())
    s = s.replace(home, "<HOME>").replace(Path(home).as_posix(), "<HOME>")
    s = re.sub(r"0x[0-9a-fA-F]{6,}", "0x?", s)
    lines = [" ".join(ln.split()) for ln in s.replace("\r\n", "\n").split("\n")]
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines)


def tracked_files(cwd=ROOT, ref=None):
    if ref:
        out = git("ls-tree", "-r", "-z", "--name-only", ref, cwd=cwd)
    else:
        out = git("ls-files", "-z", cwd=cwd)
    return sorted(p for p in out.split("\0") if p)


