_HEADING = re.compile(r"^(#+ .*|=+ .* =+|[A-Za-z][\w /().,-]{0,60}:)$")


def headings(text: str) -> list[str]:
    return sorted({re.sub(r"\d+", "9", ln) for ln in text.splitlines() if _HEADING.match(ln)})


def surface_o7(tree: Path) -> dict[str, Any]:
    out: dict[str, dict[str, Any]] = {}
    for key, argv in sorted(DOC_COMMANDS.items()):
        try:
            r = run([venv_python(tree), *argv], cwd=tree, env=oracle_env(), timeout=120)
            text = normalize_text(r.stdout + r.stderr, tree)
            out[key] = {"rc": r.returncode, "lines": len(text.splitlines()), "headings": headings(text)}
        except subprocess.TimeoutExpired:
            out[key] = {"rc": 999, "lines": 0, "headings": []}
    return {"commands": out}


def compare_o7(a: dict[str, Any], b: dict[str, Any], partial: bool = False) -> list[tuple[str, str]]:  # noqa: FBT001, RUF100  # positional flag kept: signature probed by the oracle (O5); FBT is ratchet-only
    diffs: list[tuple[str, str]] = []
    for key, r in sorted(a["commands"].items()):
        rb = b["commands"].get(key)
        if rb is None:
            diffs.append(("cmd:" + key, "command not captured"))
            continue
        if rb["rc"] != r["rc"]:
            diffs.append(("cmd:" + key, "exit {} -> {}".format(r["rc"], rb["rc"])))
        if abs(rb["lines"] - r["lines"]) > max(1, 0.1 * r["lines"]):
            diffs.append(("cmd:" + key, "output {:d} -> {:d} lines (>10%)".format(r["lines"], rb["lines"])))
        if rb["headings"] != r["headings"]:
            diffs.append(("cmd:" + key, "headings changed"))
    return diffs


# ----------------------------------------------------------------------------- O8 non-Python files


def allowlisted(path: str) -> bool:
    return any(
        fnmatch.fnmatchcase(path, pat) or (pat.endswith("/**") and path.startswith(pat[:-2])) for pat in O8_ALLOWLIST
    )


def surface_o8(commit: str, cwd: Path | str = ROOT) -> dict[str, Any]:
    base = g0_base()
    changed = git("diff", "--name-only", "--no-renames", base, commit, cwd=cwd).splitlines()
    non_py = sorted(p for p in changed if not p.endswith(".py"))
    return {"base": base, "changed_non_py": non_py, "violations": [p for p in non_py if not allowlisted(p)]}


def compare_o8(a: dict[str, Any], b: dict[str, Any], partial: bool = False) -> list[tuple[str, str]]:  # noqa: FBT001, RUF100  # positional flag kept: signature probed by the oracle (O5); FBT is ratchet-only
    return [("path:" + p, "non-Python file outside the tooling allowlist") for p in b["violations"]]


# ----------------------------------------------------------------------------- O9 test strength


def assertion_count(fn: ast.AST) -> int:
    n = 0
    for node in ast.walk(fn):
        if isinstance(node, ast.Assert):
            n += 1
        elif isinstance(node, (ast.With, ast.AsyncWith)):
            for item in node.items:
                c = item.context_expr
                if isinstance(c, ast.Call):
                    name = ast.unparse(c.func)
                    if name.endswith(("raises", "warns", "deprecated_call")):
                        n += 1
        elif isinstance(node, ast.Call):
            name = ast.unparse(node.func)
            last = name.rsplit(".", 1)[-1]
            if last.startswith("assert") or name in ("pytest.fail", "fail"):
                n += 1
    return n


def test_strength(tree_root: Path, files: list[str] | None = None) -> dict[str, Any]:  # noqa: PT028  # not a pytest test: the O9 capture
    files = files or [f for f in tracked_files(tree_root) if f.startswith("tests/") and f.endswith(".py")]
    out: dict[str, int] = {}
    for f in files:
        tree = parse_file(tree_root / f)
        if tree is None:
            continue
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test"):
                out[f"{f}::{node.name}"] = assertion_count(node)
            elif isinstance(node, ast.ClassDef) and node.name.startswith("Test"):
                for sub in node.body:
                    if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)) and sub.name.startswith("test"):
                        out[f"{f}::{node.name}::{sub.name}"] = assertion_count(sub)
    return {"tests": dict(sorted(out.items())), "total": sum(out.values())}


def compare_o9(a: dict[str, Any], b: dict[str, Any], partial: bool = False) -> list[tuple[str, str]]:  # noqa: FBT001, RUF100  # positional flag kept: signature probed by the oracle (O5); FBT is ratchet-only
    diffs: list[tuple[str, str]] = []
    for k, n in sorted(a["tests"].items()):
        nb = b["tests"].get(k)
        if nb is None:
            diffs.append(("test:" + k, "test function gone"))
        elif nb < n:
            diffs.append(("test:" + k, f"assertions {n:d} -> {nb:d}"))
    if b["total"] < a["total"]:
        diffs.append(("total", "total assertions {:d} -> {:d}".format(a["total"], b["total"])))
    return diffs


# ----------------------------------------------------------------------------- O10 coverage


def surface_o10(tree: Path, raw: Path, select: Sequence[str] = ()) -> dict[str, Any]:
    data = raw / ".coverage"
    env = oracle_env()
    cmd = [
        "uv",
        "run",
        "--frozen",
        "--with",
        "coverage==" + COVERAGE_VERSION,
        "python",
        "-m",
        "coverage",
        "run",
        "--branch",
        "--source=" + ",".join(COVERAGE_SOURCES),
        "--data-file=" + str(data),
        "-m",
        "pytest",
        "-q",
        "-p",
        "no:cacheprovider",
        "--continue-on-collection-errors",
        *select,
    ]
    r = run_logged(cmd, raw / "O10-run.log", cwd=tree, env=env, timeout=SUITE_TIMEOUT_S)
    js = raw / "coverage.json"
    run(
        [
            "uv",
            "run",
            "--frozen",
            "--with",
            "coverage==" + COVERAGE_VERSION,
            "python",
            "-m",
            "coverage",
            "json",
            "--data-file=" + str(data),
            "-o",
            str(js),
        ],
        cwd=tree,
        env=env,
        check=True,
        timeout=600,
    )
    files = load_json(js)["files"]
    agg: dict[str, list[int]] = {}
    for path, d in files.items():
        rel = (
            Path(path).resolve().relative_to(tree.resolve()).as_posix()
            if Path(path).is_absolute()
            else path.replace("\\", "/")
        )
        pkg = rel.split("/", 1)[0]
        s = d["summary"]
        a = agg.setdefault(pkg, [0, 0])
        a[0] += s["covered_lines"] + s.get("covered_branches", 0)
        a[1] += s["num_statements"] + s.get("num_branches", 0)
    pct = {k: round(100.0 * c / t, 2) if t else 100.0 for k, (c, t) in sorted(agg.items())}
    return {"packages": pct, "suite_exitstatus": r.returncode, "coverage_version": COVERAGE_VERSION}


def compare_o10(a: dict[str, Any], b: dict[str, Any], partial: bool = False) -> list[tuple[str, str]]:  # noqa: FBT001, RUF100  # positional flag kept: signature probed by the oracle (O5); FBT is ratchet-only
    diffs: list[tuple[str, str]] = []
    for pkg, p in sorted(a["packages"].items()):
        pb = b["packages"].get(pkg)
        if pb is None or pb < p - 0.5:
            diffs.append(("cov:" + pkg, f"{p:.2f} -> {pb} (drop > 0.5 pp)"))
    return diffs


# ----------------------------------------------------------------------------- snapshot / compare


def snapshot(
    label: str,
    ref: str = "HEAD",
    runs: int = 3,
    reruns: int = 2,
    components: list[str] | None = None,
    modules: Collection[str] | None = None,
    tree: Path | None = None,
    mutate: Callable[[Path], object] | None = None,
    select: Sequence[str] = (),
    python: str | None = None,
) -> Path:
    components = components or list(COMPONENTS)
    dest = SNAPSHOTS / label
    raw = dest / "raw"
    raw.mkdir(parents=True, exist_ok=True)
    commit = git("rev-parse", ref).strip()
    ctx = run_tree(commit, python) if tree is None else contextlib.nullcontext(tree)
    with ctx as t:
        if mutate:
            mutate(t)
        dirty = bool(git_status_set(t))
        inv = build_inventory(t)
        graph = RepoGraph(t, [f for f in tracked_files(t) if f.endswith(".py")])
        tree_python = run([venv_python(t), "-c", "import sys;print(sys.version.split()[0])"]).stdout.strip()
        common = {
            "commit": commit,
            "digest": relevant_digest(commit),
            "dirty": dirty,
            "created": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
            "select": list(select),
        }

        def put(comp: str, data: dict[str, Any]) -> None:
            data["_meta"] = dict(common, partial_modules=sorted(modules) if modules else None)
            dump_json(dest / (comp + ".json"), data)
            progress(f"{comp} captured")

        if "O8" in components:
            put("O8", surface_o8(commit))
        if "O9" in components:
            put("O9", test_strength(t))
        if "O2" in components:
            put(
                "O2",
                {
                    "note": "O2 is evaluated at compare time over the format commits between "
                    "the two snapshots (oracle.py ast-equal)."
                },
            )
        if "O3" in components or "O5" in components:
            o3, o5 = probe_modules(t, inv, graph, raw, modules)
            if "O3" in components:
                put("O3", o3)
            if "O5" in components:
                put("O5", o5)
        if "O4" in components:
            put("O4", surface_o4(t, inv, graph, raw))
        if "O6" in components:
            put("O6", surface_o6(t, raw))
        if "O7" in components:
            put("O7", surface_o7(t))
        if "O10" in components:
            put("O10", surface_o10(t, raw, select))
        if "O1" in components:
            put("O1", suite_runs(t, raw, runs, reruns, select))
    meta_path = dest / "meta.json"
    meta: dict[str, Any] = load_json(meta_path) if meta_path.exists() else {}
    meta.update(
        {
            "label": label,
            "commit": commit,
            "digest": common["digest"],
            "dirty": dirty,
            "python": run([sys.executable, "-c", "import sys;print(sys.version.split()[0])"]).stdout.strip(),
            "tree_python": tree_python,
            "platform": sys.platform,
            "uv": run(["uv", "--version"]).stdout.strip(),
        }
    )
    meta.setdefault("components", {})
    for c in components:
        meta["components"][c] = common["created"]
    meta["raw_digests"] = {
        p.relative_to(raw).as_posix(): sha256_file(p)
        for p in sorted(raw.rglob("*"))
        if p.is_file() and p.suffix in (".log", ".xml") and "rerun" not in p.parts
    }
    if "O1" in components:
        meta["suite_runs"] = runs
        meta["reruns"] = reruns
    dump_json(meta_path, meta)
    return dest


