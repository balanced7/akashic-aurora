def _uvx(tool: str, args: Sequence[str], cwd: Path, timeout: float = 3600) -> subprocess.CompletedProcess[str]:
    return run(["uvx", f"{tool}@{MEASURE_TOOLS[tool]}", *args], cwd=cwd, env=oracle_env(), timeout=timeout)


def _ruff_cfg(d: Path, select: list[str], target: str = "py311", line_length: int = 100) -> Path:
    cfg = d / ("ruff-{}-{:d}.toml".format("-".join(select)[:20], line_length))
    cfg.write_text(
        (
            f'target-version = "{target}"\nline-length = {line_length:d}\n[lint]\nselect = {json.dumps(select)}\nignore = {json.dumps(TARGET_IGNORE)}\n'
            '[lint.per-file-ignores]\n"tests/**" = ["S101"]\n"scripts/**" = ["T20"]\n'
        ),
        encoding="utf-8",
    )
    return cfg


def _rule_counts(stdout: str) -> dict[str, int]:
    counts: dict[str, int] = {}
    for d in json.loads(stdout or "[]"):
        code = d.get("code") or "syntax-error"
        counts[code] = counts.get(code, 0) + 1
    return dict(sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))


def measure(ref: str) -> dict[str, Any]:
    out: dict[str, Any] = {
        "ref": git("rev-parse", ref).strip(),
        "tools": MEASURE_TOOLS,
        "ruff_config": {
            "select": TARGET_SELECT,
            "ignore": TARGET_IGNORE,
            "per_file_ignores": {"tests/**": ["S101"], "scripts/**": ["T20"]},
            "target_version": "py311 (requires-python >=3.11)",
        },
    }
    cfgdir = Path(tempfile.mkdtemp(prefix="aurora-measure-cfg-"))
    try:
        with scratch_tree(out["ref"], "aurora-measure-") as t:
            inv = build_inventory(t)
            files = [f for f in inv["in_scope"] if (t / f).exists()]
            out["in_scope_files"] = len(files)
            out["in_scope_lines"] = sum(inv["files"][f]["lines"] for f in files)
            r = _uvx(
                "ruff",
                [
                    "check",
                    "--config",
                    str(_ruff_cfg(cfgdir, TARGET_SELECT)),
                    "--output-format",
                    "json",
                    "--exit-zero",
                    *files,
                ],
                t,
            )
            rules = _rule_counts(r.stdout)
            out["ruff_target"] = {"total": sum(rules.values()), "by_rule": rules}
            fam: dict[str, int] = {}
            for code, n in rules.items():
                f = re.match(r"[A-Z]+", code)
                f = f.group(0) if f else code
                fam[f] = fam.get(f, 0) + n
            out["ruff_target"]["by_prefix"] = dict(sorted(fam.items(), key=lambda kv: -kv[1]))
            r = _uvx(
                "ruff",
                [
                    "check",
                    "--config",
                    str(_ruff_cfg(cfgdir, STRETCH)),
                    "--output-format",
                    "json",
                    "--exit-zero",
                    *files,
                ],
                t,
            )
            stretch: dict[str, int] = {}
            for code, n in _rule_counts(r.stdout).items():
                f = next((x for x in sorted(STRETCH, key=len, reverse=True) if code.startswith(x)), code)
                stretch[f] = stretch.get(f, 0) + n
            out["ruff_stretch"] = stretch
            out["ruff_format"] = {}
            for ll in (100, 120):
                # concise output: ruff 0.16.9's default "full" renderer panics on two files
                # (ruff_annotate_snippets source_map.rs:185); the formatter itself does not
                r = _uvx(
                    "ruff",
                    [
                        "format",
                        "--check",
                        "--output-format",
                        "concise",
                        "--config",
                        str(_ruff_cfg(cfgdir, ["E"], line_length=ll)),
                        *files,
                    ],
                    t,
                )
                text = r.stdout + r.stderr
                out["ruff_format"][f"line_length_{ll:d}"] = {
                    "would_reformat": len(re.findall(r"(?m): unformatted: File would be reformatted$", text)),
                    "errors": [ln for ln in text.splitlines() if ln.startswith("error")][:20],
                    "exit": r.returncode,
                }
            pyr = cfgdir / "pyrightconfig.json"
            pyr.write_text(
                json.dumps(
                    {
                        "include": [str(t / f) for f in files],
                        "typeCheckingMode": "standard",
                        "pythonVersion": "3.12",
                        "venvPath": str(t),
                        "venv": ".venv",
                        "extraPaths": [str(t)],
                    }
                ),
                encoding="utf-8",
            )
            # text output: basedpyright 1.40.1 dies in V8 (exit 245/251, no message) while
            # serialising --outputjson for this many diagnostics; the analysis itself completes
            r = _uvx("basedpyright", ["-p", str(pyr)], t)
            text = r.stdout + r.stderr
            m = re.search(r"(?m)^(\d+) errors?, (\d+) warnings?", text)
            by_rule: dict[str, int] = {}
            for rule in re.findall(r"(?m)^\s+\S.*? - error: .*?\((report\w+)\)\s*$", text):
                by_rule[rule] = by_rule.get(rule, 0) + 1
            out["basedpyright_standard"] = {
                "errors": int(m.group(1)) if m else None,
                "warnings": int(m.group(2)) if m else None,
                "exit": r.returncode,
                "by_rule_single_line": dict(sorted(by_rule.items(), key=lambda kv: -kv[1])),
                "note": "by_rule counts errors whose rule tag sits on the error line itself; "
                "multi-line messages put it on a continuation line and are counted "
                "in errors only",
            }
            r = _uvx(
                "ty", ["check", "--python", str(venv_python(t)), "--output-format", "concise", "--exit-zero", *files], t
            )
            m = re.search(r"Found (\d+) diagnostic", r.stdout + r.stderr)
            out["ty"] = {
                "diagnostics": int(m.group(1)) if m else None,
                "tail": (r.stdout + r.stderr).strip().splitlines()[-1:] if not m else [],
            }
    finally:
        _rmtree(cfgdir)
    return out


def suite_measurements(label: str) -> dict[str, Any]:
    """Durations (the 50 slowest tests, from run 1's junit xml) and coverage, from a snapshot."""
    import xml.etree.ElementTree as ET

    d = snapshot_dir(label)
    res: dict[str, Any] = {}
    xml_path = d / "raw" / "O1-run1.xml"
    if xml_path.exists():
        cases = [
            (float(tc.get("time", 0)), "{}::{}".format(tc.get("classname"), tc.get("name")))
            for tc in ET.parse(xml_path).getroot().iter("testcase")
        ]
        cases.sort(reverse=True)
        res["slowest_50"] = [{"s": round(t, 2), "test": n} for t, n in cases[:50]]
    if (d / "O1.json").exists():
        res["suite_runs_s"] = [r["duration_s"] for r in load_json(d / "O1.json")["runs"]]
        res["outcome_counts"] = [r["counts"] for r in load_json(d / "O1.json")["runs"]]
    if (d / "O10.json").exists():
        res["coverage_branch_pct"] = load_json(d / "O10.json")["packages"]
    return res


def cmd_measure(args: argparse.Namespace) -> int:
    m = measure(args.ref)
    m["suite"] = suite_measurements(args.label)
    dump_json(snapshot_dir(args.label) / "measurements.json", m)
    print(
        json.dumps(
            {
                k: (
                    v
                    if not isinstance(v, dict) or len(json.dumps(v)) < 300
                    else {kk: vv for kk, vv in cast("dict[str, Any]", v).items() if not isinstance(vv, (dict, list))}
                )
                for k, v in m.items()
                if k != "suite"
            },
            indent=1,
        )
    )
    return 0


