def _norm_doc(s: str) -> str:
    return "\n".join(ln.rstrip() for ln in inspect.cleandoc(s).splitlines()).strip()


def ast_fingerprint(src: bytes) -> str:
    tree = ast.parse(src)
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            body = node.body
            if (
                body
                and isinstance(body[0], ast.Expr)
                and isinstance(body[0].value, ast.Constant)
                and isinstance(body[0].value.value, str)
            ):
                body[0].value.value = _norm_doc(body[0].value.value)
    return ast.dump(tree, include_attributes=False)


def ast_equal(parent: str, commit: str, cwd: Path | str = ROOT) -> list[tuple[str, bool, str]]:
    out = git("diff", "--name-status", "--no-renames", parent, commit, "--", "*.py", cwd=cwd)
    results: list[tuple[str, bool, str]] = []
    for line in out.splitlines():
        status, path = line.split("\t", 1)
        if status != "M":
            results.append((path, False, f"status {status} (a format commit only modifies)"))
            continue
        a = run(["git", "show", f"{parent}:{path}"], cwd=cwd).stdout.encode("utf-8")
        b = run(["git", "show", f"{commit}:{path}"], cwd=cwd).stdout.encode("utf-8")
        try:
            ok = ast_fingerprint(a) == ast_fingerprint(b)
            results.append((path, ok, "" if ok else "AST differs"))
        except SyntaxError as e:
            results.append((path, False, f"unparseable: {e}"))
    return results


def cmd_ast_equal(args: argparse.Namespace) -> int:
    res = ast_equal(args.parent, args.commit)
    for path, ok, why in res:
        print("{} {}{}".format("EQUAL" if ok else "DIFF ", path, (" (" + why + ")") if why else ""))
    n_ok = sum(1 for _, ok, _ in res if ok)
    print(f"AST: {n_ok:d}/{len(res):d} EQUAL")
    return 0 if n_ok == len(res) else 1


def format_commits(a_commit: str | None, b_commit: str | None, cwd: Path | str = ROOT) -> list[str]:
    """Class-B commits between two snapshots: subject `style: ...` (not `style(lint): ...`)."""
    if not a_commit or not b_commit or a_commit == b_commit:
        return []
    out = git("log", "--format=%H %s", f"{a_commit}..{b_commit}", cwd=cwd, check=False)
    return [ln.split(" ", 1)[0] for ln in out.splitlines() if ln.split(" ", 1)[1].startswith("style:")]


