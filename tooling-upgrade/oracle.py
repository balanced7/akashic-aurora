def optional_import_names(tree: Path) -> set:
    """Import names of DECLARED optional dependencies: the pyproject dependency groups, the
    platform-marked dependencies, and what they pull in by name (torch) or the stdlib leaves
    out on some builds (tkinter). Any other missing module is an error, not an option."""
    names = {"torch", "transformers", "tkinter"}
    try:
        data = tomllib.loads((tree / "pyproject.toml").read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return names
    reqs = [r for g in data.get("dependency-groups", {}).values() for r in g if isinstance(r, str)]
    reqs += [r for r in data.get("project", {}).get("dependencies", []) if ";" in r]
    for r in reqs:
        dist = re.split(r"[\s<>=!~;\[]", r.strip(), maxsplit=1)[0]
        names.add(dist.lower().replace("-", "_").replace(".", "_"))
    return names


# O5 surface rule. The plan's literal rule is "__all__ if defined, else names not starting with
# _". Read literally over dir(module) it would count every `import os` as public surface, and
# G3's F401 wave (which removes unused imports by design) would then be an O5 DIFF in hundreds
# of modules. So O5 records: __all__ when defined; otherwise the names the module itself binds
# at top level (defs, classes, assignments); PLUS every name other in-repo code actually takes
# from the module (`from m import x`, `m.x`) even when m only imported it -- the re-exports the
# plan's F401 rule protects -- and, for package __init__ files, every imported name.
def surface_targets(inv: dict, modules=None):
    out = []
    for f in inv["in_scope"]:
        e = inv["files"][f]
        if e["class"] == "TEST":
            continue
        mod = e["module"] or f
        if modules and mod not in modules and f not in modules:
            continue
        out.append((f, e))
    return out


def probe_modules(tree: Path, inv: dict, graph: RepoGraph, raw: Path, modules=None):
    """O3 + O5 together: one fresh interpreter per module, 20 s each, in parallel."""
    targets = surface_targets(inv, modules)
    optional = sorted(optional_import_names(tree))
    py = venv_python(tree)
    probe = raw / "probe.py"
    probe.write_text(_PROBE, encoding="utf-8")
    work = raw / "probe"
    work.mkdir(parents=True, exist_ok=True)

    def one(item):
        f, e = item
        key = e["module"] or f
        tree_ast = graph.asts.get(f)
        defined = sorted(n for n in top_level_bindings(tree_ast, include_imports=f.endswith("__init__.py"))
                         if not n.startswith("_"))
        ext = sorted(n for n in graph.ext_names.get(f, ()) if not n.startswith("_"))
        static = {"ext": ext, "defined": defined, "optional": optional}
        if not e["import_safe"]:
            return key, f, {"status": "SKIPPED(%s)" % e.get("import_unsafe_reason", "unsafe")}, static, tree_ast
        h = sha256_bytes(f.encode())[:16]
        names_path, out_path = work / (h + ".names.json"), work / (h + ".out.json")
        names_path.write_text(json.dumps(static), encoding="utf-8")
        mod = e["module"] if e["module"] and not f.startswith(("data/", "state/")) else "-"
        try:
            # a fixed hash seed makes set/frozenset defaults print in one order (probe only;
            # the suite itself always runs with the interpreter's normal randomisation)
            run([py, probe, str(tree), mod, f, names_path, out_path], cwd=tree,
                env=oracle_env({"PYTHONHASHSEED": "0"}), timeout=IMPORT_TIMEOUT_S)
            res = load_json(out_path) if out_path.exists() else {"status": "error:no-result"}
        except subprocess.TimeoutExpired:
            res = {"status": "timeout"}
        return key, f, res, static, tree_ast

    progress("O3/O5 probing %d modules" % len(targets))
    with ThreadPoolExecutor(max_workers=min(12, (os.cpu_count() or 4))) as pool:
        results = list(pool.map(one, targets))
    o3, o5 = {}, {}
    for key, f, res, static, tree_ast in sorted(results, key=lambda r: r[0]):
        o3[key] = {"file": f, "status": res["status"]}
        if res.get("detail"):
            o3[key]["detail"] = res["detail"]
        if res["status"] == "OK":
            o5[key] = {"mode": "runtime", "names": res["names"], "sigs": res["sigs"]}
        else:
            names = static_all(tree_ast) or sorted(set(static["defined"]) | set(static["ext"]))
            o5[key] = {"mode": "static", "names": names, "sigs": static_signatures(tree_ast)}
    sensitive = sorted((inv["files"][f]["module"] or f) for f in inv["annotation_sensitive"])
    return {"modules": o3}, {"modules": o5, "sensitive": sensitive}


def compare_o3(a, b, partial=False) -> list:
    diffs = []
    for mod, r in sorted(a["modules"].items()):
        rb = b["modules"].get(mod)
        if rb is None:
            if not partial:
                diffs.append(("import:" + mod, "module no longer probed"))
        elif r["status"] == "OK" and rb["status"] != "OK":
            diffs.append(("import:" + mod, "OK -> %s" % rb["status"]))
    return diffs


def compare_o5(a, b, partial=False) -> list:
    diffs = []
    sensitive = set(a.get("sensitive", [])) | set(b.get("sensitive", []))
    for mod, s in sorted(a["modules"].items()):
        sb = b["modules"].get(mod)
        if sb is None:
            if not partial:
                diffs.append(("module:" + mod, "module surface gone"))
            continue
        for n in sorted(set(s["names"]) - set(sb["names"])):
            diffs.append(("name:%s.%s" % (mod, n), "public name disappeared"))
        if s.get("mode") != sb.get("mode"):
            continue
        for n, sig in sorted(s["sigs"].items()):
            sgb = sb["sigs"].get(n)
            if sgb is None:
                continue
            if sig["bare"] != sgb["bare"]:
                diffs.append(("sig:%s.%s" % (mod, n), "%s -> %s" % (sig["bare"], sgb["bare"])))
            elif sig["full"] != sgb["full"] and mod in sensitive:
                diffs.append(("annot:%s.%s" % (mod, n),
                              "annotation changed in an annotation-sensitive module"))
    return diffs


