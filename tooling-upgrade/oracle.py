def cmd_inventory(args: argparse.Namespace) -> int:
    inv = build_inventory(ROOT)
    if args.check:
        old = load_json(INVENTORY)
        new = json.loads(json.dumps(inv, sort_keys=True))
        old.pop("commit", None)
        new.pop("commit", None)
        if old != new:
            print("INVENTORY STALE: regenerate with `oracle.py inventory`")
            for k in sorted(set(old) | set(new)):
                if old.get(k) != new.get(k):
                    print("   key differs:", k)
            changed = sorted(
                f
                for f in set(old.get("files", {})) | set(new["files"])
                if old.get("files", {}).get(f) != new["files"].get(f)
            )
            for f in changed[:20]:
                print("   file differs:", f)
            return 1
        print("INVENTORY CURRENT: {:d} files, {}".format(len(inv["files"]), inv["counts"]))
        return 0
    if args.verify_proofs:
        return verify_proofs(load_json(INVENTORY))
    dump_json(INVENTORY, inv)
    print("inventory: {:d} files {} -> {}".format(len(inv["files"]), inv["counts"], INVENTORY.relative_to(ROOT)))
    return 0


def verify_proofs(inv: dict[str, Any]) -> int:
    bad: list[str] = []
    for f, e in inv["files"].items():
        if e["class"] != "ARCHIVAL":
            continue
        p: dict[str, Any] = e.get("proof") or {}
        if (
            not f.startswith(HISTORY_TREES)
            or p.get("history_tree") is None
            or p.get("nonarchival_importers") != []
            or p.get("path_ref_count") != 0
        ):
            bad.append(f)
    n = sum(1 for e in inv["files"].values() if e["class"] == "ARCHIVAL")
    print(f"ARCHIVAL PROOFS: {n - len(bad):d}/{n:d} complete")
    for f in bad[:20]:
        print("  missing/failed proof:", f)
    return 1 if bad else 0


# ----------------------------------------------------------------------------- the run tree


def _rmtree(path: Path) -> None:
    def onerror(func: Callable[[str], object], p: str, _exc: object) -> None:
        with contextlib.suppress(OSError):
            os.chmod(p, 0o700)
            func(p)

    shutil.rmtree(path, onerror=onerror)


def verify_checkout(tree: Path) -> None:
    """Rehash every checked-out file against the index (not git's stat cache): a byte that
    changed between git writing the file and the probes reading it -- observed in G1 as a
    single flipped bit, '}' (0x7d) -> 'u' (0x75), in one file of one run tree -- would
    otherwise be measured as a behaviour change. Raises, so the run is retried, never recorded."""
    run(["git", "update-index", "-q", "--really-refresh"], cwd=tree)
    bad = run(["git", "status", "--porcelain", "--untracked-files=no"], cwd=tree).stdout.strip()
    if bad:
        raise RuntimeError(f"run tree {tree} does not match its commit after checkout:\n{bad[:2000]}")


@contextlib.contextmanager
def scratch_tree(ref: str, prefix: str = "aurora-scratch-") -> Generator[Path, None, None]:
    """Like run_tree, at a random path: for work that never compares help text (measurements),
    so it can run while a snapshot holds the fixed path."""
    base = Path(tempfile.mkdtemp(prefix=prefix))
    tree = base / "aurora-scratch"
    git("worktree", "add", "--detach", str(tree), ref)
    try:
        run(["uv", "sync", "--frozen", "--quiet"], cwd=tree, env=oracle_env(), check=True, timeout=1800)
        yield tree
    finally:
        _rmtree(base)
        git("worktree", "prune", check=False)


def _owner_alive(o: dict[str, Any]) -> bool:
    """Is the process that owns the fixed run tree still alive? POSIX: signal 0. Windows has no
    harmless probe in the stdlib (os.kill terminates there), so a tree younger than the longest
    snapshot (6 h) counts as owned."""
    if os.name == "posix":
        try:
            os.kill(int(o.get("pid", 0)), 0)
            return True
        except (OSError, ValueError):
            return False
    return time.time() - float(o.get("started", 0)) < 6 * 3600


@contextlib.contextmanager
def run_tree(ref: str, python: str | None = None) -> Generator[Path, None, None]:
    """A detached throwaway worktree of `ref` with its own frozen venv. Removed afterwards by
    deleting the directory and pruning (never a forced git operation).

    The path is FIXED, not mkdtemp-random: argparse wraps defaults that embed it (e.g. a
    `--out-dir` default), and a random path would wrap differently on every snapshot. So only
    one snapshot runs at a time; a leftover tree from a crashed run is the oracle's own and is
    removed first."""
    base = Path(tempfile.gettempdir()) / "aurora-oracle-run"
    owner = base / "owner.json"
    if base.exists():
        if owner.exists() and _owner_alive(load_json(owner)):
            raise RuntimeError(
                "another snapshot is running in {} (owner {}); one at a time".format(
                    base, owner.read_text(encoding="utf-8").strip()
                )
            )
        _rmtree(base)  # a crashed run's leftover: the oracle's own scratch
        git("worktree", "prune", check=False)
    base.mkdir(parents=True)
    dump_json(owner, {"pid": os.getpid(), "started": time.time()})
    tree = base / "aurora-oracle"
    git("worktree", "add", "--detach", str(tree), ref)
    try:
        verify_checkout(tree)
        # `python`: measure a candidate interpreter (plan G1.P2) without committing a pin.
        run(
            ["uv", "sync", "--frozen", "--quiet"] + (["--python", python] if python else []),
            cwd=tree,
            env=oracle_env(),
            check=True,
            timeout=1800,
        )
        yield tree
    finally:
        _rmtree(base)
        git("worktree", "prune", check=False)


def git_status_set(tree: Path) -> set[str]:
    out = run(["git", "status", "--porcelain", "--untracked-files=all"], cwd=tree).stdout
    return set(out.splitlines())


def written_paths(tree: Path, before: dict[str, int]) -> tuple[set[str], dict[str, int]]:
    """Return the paths written since `before` was taken, and the new stamp.

    Paths are tracked, or untracked and not ignored. A write is a new path or a changed mtime:
    a rewrite with identical bytes is still a side effect, which `git status` alone cannot see.
    """
    out = run(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"], cwd=tree).stdout
    now: dict[str, int] = {}
    for rel in filter(None, out.split("\0")):
        try:
            now[rel] = (tree / rel).stat().st_mtime_ns
        except OSError:
            continue
    changed = {rel for rel, m in now.items() if before.get(rel) != m}
    if before:
        changed |= set(before) - set(now)
    return (changed if before else set()), now


# ----------------------------------------------------------------------------- O1 test outcomes


def _final_outcome(rec: dict[str, Any]) -> str:
    if rec.get("setup") == "failed" or rec.get("teardown") == "failed":
        return "error"
    if rec.get("setup") == "skipped":
        return "skipped"
    return rec.get("call") or rec.get("setup") or "unknown"


def _pytest(
    tree: Path, args: Sequence[object], out_json: Path, timeout: float | None, log: Path | None = None
) -> tuple[subprocess.CompletedProcess[str], dict[str, Any]]:
    env = oracle_env({"PYTHONPATH": str(PLUGIN_DIR), "AURORA_ORACLE_OUT": str(out_json)})
    cmd = [venv_python(tree), "-m", "pytest", *args, "-p", "aurora_oracle_plugin"]
    t0 = time.time()
    r = (
        run_logged(cmd, log, cwd=tree, env=env, timeout=timeout)
        if log
        else run(cmd, cwd=tree, env=env, timeout=timeout)
    )
    data: dict[str, Any] = (
        load_json(out_json) if out_json.exists() else {"results": {}, "collect_errors": [], "exitstatus": r.returncode}
    )
    data["duration_s"] = round(time.time() - t0, 1)
    return r, data


def suite_runs(tree: Path, raw: Path, runs: int, reruns: int, select: Sequence[str] = ()) -> dict[str, Any]:
    run_data: list[dict[str, Any]] = []
    side_effects: list[list[str]] = []
    for i in range(1, runs + 1):
        out = raw / (f"O1-run{i:d}.json")
        before = git_status_set(tree)
        progress(f"O1 suite run {i:d}/{runs:d}")
        _r, data = _pytest(
            tree,
            [
                "-q",
                "-rfE",
                "-p",
                "no:cacheprovider",
                "--continue-on-collection-errors",
                "--junitxml=%s" % (raw / (f"O1-run{i:d}.xml")),
                *select,
            ],
            out,
            SUITE_TIMEOUT_S,
            log=raw / (f"O1-run{i:d}.log"),
        )
        run_data.append(data)
        # what the suite does to the checkout it runs in (informational; never compared)
        side_effects.append(sorted(x[3:] for x in git_status_set(tree) - before))
    tests: dict[str, dict[str, Any]] = {}
    for i, data in enumerate(run_data):
        for nid, rec in data["results"].items():
            tests.setdefault(nid, {"outcomes": [None] * runs})["outcomes"][i] = _final_outcome(rec)
    # Every id that did not pass somewhere is rerun alone, twice, so "fails reproducibly" is a
    # measured fact rather than a single-run accident.
    todo = [n for n, t in tests.items() if not all(o in ("passed", "skipped", "xfailed") for o in t["outcomes"] if o)]
    progress(f"O1 isolated reruns: {len(todo):d} ids x {reruns:d}")
    for k, nid in enumerate(sorted(todo)):
        t = tests[nid]
        if k % 10 == 0:
            progress(f"  rerun {k + 1:d}/{len(todo):d}")
        rerun_outcomes: list[str] = []
        t["reruns"] = rerun_outcomes
        for k in range(reruns):
            out = raw / "rerun" / (f"{sha256_bytes(nid.encode())[:16]}-{k:d}.json")
            out.parent.mkdir(parents=True, exist_ok=True)
            _r, d = _pytest(tree, [nid, "-q", "-p", "no:cacheprovider", "-p", "no:randomly"], out, 600)
            rerun_outcomes.append(_final_outcome(d["results"].get(nid, {})))
    for t in tests.values():
        t["class"] = o1_class(t["outcomes"])
    tests = {public_id(k): v for k, v in tests.items()}
    return {
        "runs": [
            {
                "exitstatus": d["exitstatus"],
                "duration_s": d["duration_s"],
                "collect_errors": sorted(d["collect_errors"]),
                "counts": _counts(d),
                "tree_side_effects": fx,
            }
            for d, fx in zip(run_data, side_effects, strict=False)
        ],
        "tests": tests,
    }


def _counts(data: dict[str, Any]) -> dict[str, int]:
    c: dict[str, int] = {}
    for rec in data["results"].values():
        o = _final_outcome(rec)
        c[o] = c.get(o, 0) + 1
    return dict(sorted(c.items()))


def o1_class(outcomes: Iterable[str | None]) -> str:
    seen = {o for o in outcomes if o is not None}
    if not seen:
        return "uncollected"
    if seen == {"passed"}:
        return "stable-pass"
    if seen <= {"failed", "error"}:
        return "stable-fail"
    if seen == {"skipped"}:
        return "skip"
    if seen == {"xfailed"}:
        return "xfail"
    return "flaky"


def fails_reproducibly(t: dict[str, Any]) -> bool:
    return (
        any(o in ("failed", "error") for o in t["outcomes"])
        and len(t.get("reruns", [])) >= 2
        and all(o in ("failed", "error", "unknown") for o in t["reruns"])
    )


def o1_ran(run: dict[str, Any]) -> int:
    c = run["counts"]
    return c.get("passed", 0) + c.get("failed", 0) + c.get("error", 0)


def public_id(nid: str) -> str:
    """The node id as O1 stores it: parameter text replaced by its sha256 prefix. Parametrize
    ids can carry fixture VALUES -- this repo's secret-scanner tests parametrize on fake
    credential-shaped strings -- and copying them into a tracked snapshot moves them out of the
    files check_secrets allowlists. Hashing keeps matching exact and the values where they are."""
    if "[" in nid and nid.endswith("]") and "[#" not in nid:
        base, params = nid.split("[", 1)
        return "{}[#{}]".format(base, sha256_bytes(params[:-1].encode("utf-8"))[:12])
    return nid


def id_base(nid: str) -> str:
    return nid.split("[", 1)[0]


def _per_run(s: dict[str, Any]) -> list[dict[str, dict[str, Any]]]:
    """[{base: {id: outcome}}] for each run."""
    out: list[dict[str, dict[str, Any]]] = [{} for _ in s["runs"]]
    for nid, t in s["tests"].items():
        for i, o in enumerate(t["outcomes"]):
            if o is not None and i < len(out):
                out[i].setdefault(id_base(nid), {})[nid] = o
    return out


def volatile_bases(s: dict[str, Any]) -> set[str]:
    """Parametrized tests whose ids differ between runs of ONE snapshot (an id built from a
    timestamp or a fresh signature): they can only be compared by count, never by id."""
    runs = _per_run(s)
    bases: set[str] = set[str]().union(*runs) if runs else set()
    return {b for b in bases if len({frozenset(r.get(b, {})) for r in runs}) > 1}


def compare_o1(a: dict[str, Any], b: dict[str, Any], partial: bool = False) -> list[tuple[str, str]]:  # noqa: FBT001, RUF100  # positional flag kept: signature probed by the oracle (O5); FBT is ratchet-only
    diffs: list[tuple[str, str]] = []
    volatile = volatile_bases(a) | volatile_bases(b)
    ra, rb = _per_run(a), _per_run(b)
    for base in sorted(volatile):

        def cnt(runs: list[dict[str, dict[str, Any]]], base: str = base) -> int:
            return min((len(r.get(base, {})) for r in runs), default=0)

        def ok(runs: list[dict[str, dict[str, Any]]], base: str = base) -> int:
            return min(
                (sum(o == "passed" for o in r.get(base, {}).values()) for r in runs),
                default=0,
            )

        if cnt(rb) < cnt(ra):
            diffs.append(("volatile:" + base, f"collects {cnt(rb):d} < baseline {cnt(ra):d} per run"))
        elif ok(rb) < ok(ra):
            diffs.append(("volatile:" + base, f"passes {ok(rb):d} < baseline {ok(ra):d} per run"))
    for nid, t in sorted(a["tests"].items()):
        if id_base(nid) in volatile:
            continue
        nb = b["tests"].get(nid)
        if nb is None or nb["class"] == "uncollected":
            diffs.append(("id:" + nid, "no longer collected"))
        elif t["class"] == "stable-pass" and fails_reproducibly(nb):
            diffs.append(("regressed:" + nid, "stable-pass now fails reproducibly"))

    def skips(s: dict[str, Any]) -> int:
        return max((r["counts"].get("skipped", 0) for r in s["runs"]), default=0)

    if skips(b) > skips(a):
        diffs.append(("skips", f"skip count {skips(b):d} > baseline {skips(a):d}"))

    def cerr(s: dict[str, Any]) -> int:
        return max((len(r["collect_errors"]) for r in s["runs"]), default=0)

    if cerr(b) > cerr(a):
        diffs.append(("collect-errors", f"collection errors {cerr(b):d} > baseline {cerr(a):d}"))

    def ran(s: dict[str, Any]) -> int:
        return min((o1_ran(r) for r in s["runs"]), default=0)

    if ran(b) < ran(a):
        diffs.append(("run-count", f"tests run {ran(b):d} < baseline {ran(a):d} (T7)"))
    return diffs


