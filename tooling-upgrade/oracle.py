def mcp_server_script(tree: Path):
    cfg = json.loads((tree / ".mcp.json").read_text(encoding="utf-8"))
    name, server = sorted(cfg["mcpServers"].items())[0]
    args = server.get("args", [])
    script = next((a for a in args if a.endswith(".py")), None)
    return name, server, script


def mcp_tools_inprocess(tree: Path, raw: Path):
    _name, _server, script = mcp_server_script(tree)
    probe = raw / "mcp_probe.py"
    probe.write_text(_MCP_PROBE, encoding="utf-8")
    out = raw / "mcp_tools.json"
    r = run([venv_python(tree), probe, str(tree), script, out], cwd=tree, env=oracle_env(),
            timeout=60)
    if r.returncode != 0 or not out.exists():
        raise RuntimeError("in-process MCP capture failed: " + (r.stderr or r.stdout)[-500:])
    return load_json(out)


def mcp_tools_stdio(tree: Path, timeout=IMPORT_TIMEOUT_S):
    """Fallback: launch the server as .mcp.json says (command `uv` -> the tree's venv python)
    and speak newline-delimited JSON-RPC: initialize, initialized, tools/list."""
    _name, server, script = mcp_server_script(tree)
    cmd = [str(venv_python(tree)), script] if server.get("command") == "uv" else \
        [server["command"], *server.get("args", [])]
    p = subprocess.Popen(cmd, cwd=str(tree), env=oracle_env(server.get("env")),
                         stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                         text=True, encoding="utf-8")
    msgs = [
        {"jsonrpc": "2.0", "id": 1, "method": "initialize",
         "params": {"protocolVersion": "2025-06-18", "capabilities": {},
                    "clientInfo": {"name": "aurora-oracle", "version": "1"}}},
        {"jsonrpc": "2.0", "method": "notifications/initialized"},
        {"jsonrpc": "2.0", "id": 2, "method": "tools/list"},
    ]
    try:
        p.stdin.write("".join(json.dumps(m) + "\n" for m in msgs))
        p.stdin.flush()
        deadline = time.time() + timeout
        tools, cursor_msgs = None, 0
        while time.time() < deadline:
            line = p.stdout.readline()
            if not line:
                break
            try:
                msg = json.loads(line)
            except json.JSONDecodeError:
                continue
            if msg.get("id") == 2:
                tools = msg.get("result", {}).get("tools")
                if msg.get("result", {}).get("nextCursor") and cursor_msgs < 50:
                    cursor_msgs += 1
                break
        if tools is None:
            raise RuntimeError("no tools/list response within %ss" % timeout)
        return tools
    finally:
        p.kill()
        p.wait(timeout=10)


def surface_o4(tree: Path, inv: dict, graph: RepoGraph, raw: Path) -> dict:
    helps, verbs = {}, {}
    before = git_status_set(tree)
    clis = inv["entry_points"]["argparse_cli"]
    for k, f in enumerate(clis):
        if k % 25 == 0:
            progress("O4 --help %d/%d" % (k + 1, len(clis)))
        try:
            r = run([venv_python(tree), f, "--help"], cwd=tree, env=oracle_env(),
                    timeout=HELP_TIMEOUT_S)
            item = {"rc": r.returncode, "text": normalize_text(r.stdout, tree)}
            if r.returncode != 0:
                err = normalize_text(r.stderr, tree).splitlines()
                item["stderr_last"] = err[-1] if err else ""
        except subprocess.TimeoutExpired:
            item = {"rc": None, "text": "", "na": "timeout under --help (%ss)" % HELP_TIMEOUT_S}
        after = git_status_set(tree)
        if after - before:
            item = {"rc": None, "text": "", "na": "side effect under --help: " +
                    ", ".join(sorted(x[3:] for x in after - before))[:300]}
            before = after
        helps[f] = item
        v = add_parser_verbs(graph.asts.get(f))
        if v:
            verbs[f] = v
    try:
        tools, via = mcp_tools_inprocess(tree, raw), "in-process"
    except Exception as e:  # plan G0 Fallback: capture over stdio with a 20 s timeout
        (raw / "mcp_inprocess_error.txt").write_text(str(e), encoding="utf-8")
        tools, via = mcp_tools_stdio(tree), "stdio"
    mcp = {t["name"]: {k: t[k] for k in sorted(t) if k in ("name", "description", "inputSchema",
                                                          "outputSchema", "annotations", "title")}
           for t in tools}
    return {"help": helps, "verbs": verbs, "mcp": {"via": via, "tools": mcp}}


def compare_o4(a, b, partial=False) -> list:
    diffs = []
    for f, h in sorted(a["help"].items()):
        hb = b["help"].get(f)
        if hb is None:
            if not partial:
                diffs.append(("help:" + f, "entry point gone"))
        elif any(h.get(k) != hb.get(k) for k in ("rc", "text", "na", "stderr_last")):
            diffs.append(("help:" + f, "--help output or exit code changed"))
    for f, v in sorted(a["verbs"].items()):
        missing = set(v) - set(b["verbs"].get(f, []))
        if missing:
            diffs.append(("verbs:" + f, "verbs gone: " + ", ".join(sorted(missing))))
    ta, tb = a["mcp"]["tools"], b["mcp"]["tools"]
    for name in sorted(set(ta) | set(tb)):
        if name not in tb:
            diffs.append(("mcp:" + name, "tool gone"))
        elif name not in ta:
            diffs.append(("mcp:" + name, "tool added"))
        elif json.dumps(ta[name], sort_keys=True) != json.dumps(tb[name], sort_keys=True):
            diffs.append(("mcp:" + name, "tool schema or description changed"))
    return diffs


