_PATH_TOKEN = re.compile(r"[A-Za-z0-9_./\\-]+\.py\b")
_DOTTED_TOKEN = re.compile(r"\b[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)+\b")


# A tool's exclusion list names the ARCHIVAL paths because they are archival (G2 wrote the ruff,
# basedpyright and ty excludes from this very inventory), so a path's appearance there is not a
# use of it; without this, excluding a file failed its own proof. The lists are read as TOML
# data, never matched as text, and a token is discounted only when EVERY occurrence of it in
# pyproject.toml is one of those list entries: any other mention (another key, a comment, a
# task command) still counts as a reference.
EXCLUSION_KEYS: tuple[tuple[str, ...], ...] = (
    ("tool", "ruff", "extend-exclude"),
    ("tool", "basedpyright", "exclude"),
    ("tool", "ty", "src", "exclude"),
)


def _norm_path_token(t: str) -> str:
    return t.replace("\\", "/").lstrip("./") if not t.startswith("../") else t.replace("\\", "/")


def _exclusion_entries(text: str) -> list[str]:
    """Return the string entries of pyproject.toml's EXCLUSION_KEYS lists ([] if unparseable)."""
    try:
        data: object = tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        return []
    out: list[str] = []
    for keys in EXCLUSION_KEYS:
        node: object = data
        for k in keys:
            node = cast("dict[str, object]", node).get(k) if isinstance(node, dict) else None
        if isinstance(node, list):
            out.extend(e for e in cast("list[object]", node) if isinstance(e, str))
    return out


def only_in_exclusions(rel: str, text: str) -> tuple[set[str], set[str]]:
    """Path and dotted tokens of `text` whose every occurrence is an exclusion-list entry."""
    if rel != "pyproject.toml" or "\\" in text:
        # Every TOML escape and line continuation needs a backslash; without one, each parsed
        # entry IS its raw spelling, so counting parsed entries against raw text is exact. With
        # one, a parsed entry could "use up" a real mention elsewhere: discount nothing.
        return set(), set()
    entries = _exclusion_entries(text)
    if not entries:
        return set(), set()
    excl_paths = Counter(_norm_path_token(t) for e in entries for t in _PATH_TOKEN.findall(e))
    excl_dotted = Counter(t for e in entries for t in _DOTTED_TOKEN.findall(e))
    all_paths = Counter(_norm_path_token(t) for t in _PATH_TOKEN.findall(text))
    all_dotted = Counter(_DOTTED_TOKEN.findall(text))
    return (
        {t for t, n in excl_paths.items() if all_paths[t] <= n},
        {t for t, n in excl_dotted.items() if all_dotted[t] <= n},
    )


def _text_tokens(tree_root: Path, files: list[str]) -> dict[str, tuple[set[str], set[str]]]:
    """Per non-.py-or-.py tracked text file: the .py path tokens and dotted tokens it contains."""
    out: dict[str, tuple[set[str], set[str]]] = {}
    for f in files:
        p = tree_root / f
        try:
            if p.stat().st_size > 4_000_000:
                continue
            text = p.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        paths = {_norm_path_token(t) for t in _PATH_TOKEN.findall(text)}
        dotted: set[str] = (
            set(_DOTTED_TOKEN.findall(text))
            if f.endswith(
                (".py", ".json", ".toml", ".yml", ".yaml", ".md", ".sh", ".ps1", ".cmd", ".bat", ".txt", ".cfg", ".ini")
            )
            or "/" not in f
            else set()
        )
        only_paths, only_dotted = only_in_exclusions(f, text)
        out[f] = (paths - only_paths, dotted - only_dotted)
    return out


def _referenced(cand: str, paths: set[str], unique_base: set[str]) -> bool:
    base = cand.rsplit("/", 1)[-1]
    for t in paths:
        t2 = t.split("../")[-1]
        if t2 == cand or t2.endswith("/" + cand) or ("/" in t2 and cand.endswith("/" + t2)):
            return True
        if t2 == base and base in unique_base:
            return True
    return False


def classify(rel: str) -> str:
    if rel.startswith("tests/"):
        return "TEST"
    if rel.startswith(TOOLING_ROOTS):
        return "TOOLING"
    if rel.startswith("scripts/"):
        return "SCRIPT"
    if rel.startswith(RUNTIME_ROOTS) or "/" not in rel:
        return "RUNTIME"
    return "SCRIPT"


def build_inventory(tree_root: Path = ROOT) -> dict[str, Any]:
    files = tracked_files(tree_root)
    pys = [f for f in files if f.endswith(".py")]
    graph = RepoGraph(tree_root, pys)
    tokens = _text_tokens(tree_root, files)
    basenames: dict[str, list[str]] = {}
    for f in pys:
        basenames.setdefault(f.rsplit("/", 1)[-1], []).append(f)
    unique_base = {b for b, fs in basenames.items() if len(fs) == 1}

    candidates = {f for f in pys if is_history(f)}
    # Fixpoint: a candidate that fails its proof is in scope, and then ITS imports and path
    # references count as non-archival evidence against the others.
    archival = set(candidates)
    rev = graph.reverse()
    proofs: dict[str, dict[str, Any]] = {}
    changed = True
    while changed:
        changed = False
        # The oracle's own records (inventory.json, snapshots, ledger) list every path by design;
        # they are bookkeeping about the repo, not references from it, so they prove nothing.
        nonarch_files = [
            f
            for f in files
            if not (is_history(f) and (f in archival or not f.endswith(".py")))
            and not (f.startswith("tooling-upgrade/") and not f.endswith(".py"))
        ]
        for c in sorted(archival):
            importers = sorted(i for i in rev.get(c, ()) if i not in archival)
            refs: list[str] = []
            dotted = dotted_name(c)
            for f in nonarch_files:
                if f == c or f not in tokens:
                    continue
                paths, dts = tokens[f]
                if _referenced(c, paths, unique_base) or (dotted and dotted in dts):
                    refs.append(f)
            proofs[c] = {
                "history_tree": next(h for h in HISTORY_TREES if c.startswith(h)),
                "nonarchival_importers": importers,
                "path_refs": refs[:20],
                "path_ref_count": len(refs),
            }
            if importers or refs:
                archival.discard(c)
                changed = True

    entries: dict[str, dict[str, Any]] = {}
    for f in pys:
        tree = graph.asts[f]
        e: dict[str, Any]
        if f in archival:
            e = {"class": "ARCHIVAL", "proof": proofs[f]}
        else:
            e = {"class": classify(f)}
            if f in proofs:
                e["archival_rejected"] = {k: v for k, v in proofs[f].items() if v}
        safe, why = import_safe(tree)
        e.update(
            {
                "module": dotted_name(f),
                "parse_ok": tree is not None,
                "main_guard": has_main_guard(tree),
                "argparse": uses_argparse(tree),
                "import_safe": safe,
            }
        )
        if why:
            e["import_unsafe_reason"] = why
        trig = annotation_triggers(tree)
        if trig:
            e["annotation_triggers"] = trig
        e["lines"] = len((tree_root / f).read_bytes().splitlines())
        entries[f] = e

    in_scope = sorted(f for f, e in entries.items() if e["class"] != "ARCHIVAL")
    entry_points = sorted(f for f in in_scope if entries[f]["main_guard"] and entries[f]["class"] != "TEST")
    sensitive = sorted(f for f in in_scope if entries[f].get("annotation_triggers") and entries[f]["class"] != "TEST")
    req_consumers = sorted(
        f
        for f, (_paths, _) in tokens.items()
        if not is_history(f) and not f.startswith("tooling-upgrade/") and _mentions_requirements(tree_root / f)
    )
    counts: dict[str, int] = {}
    for e in entries.values():
        counts[e["class"]] = counts.get(e["class"], 0) + 1
    return {
        "schema": 1,
        "commit": git("rev-parse", "HEAD", cwd=tree_root).strip(),
        "counts": dict(sorted(counts.items())),
        "files": entries,
        "in_scope": in_scope,
        "archival": sorted(archival),
        "archival_excludes": _archival_dirs(archival, pys),
        "entry_points": {
            "main_modules": entry_points,
            "argparse_cli": [f for f in entry_points if entries[f]["argparse"]],
            "project_scripts": _project_scripts(tree_root),
            "hook_scripts": sorted(f for f in in_scope if f.startswith("scripts/githooks/")),
            "doc_commands": DOC_COMMANDS,
        },
        "annotation_sensitive": sensitive,
        "annotation_sensitive_protocol": sorted(
            f for f in sensitive if {"FastMCP", "@*.tool decorator"} & set(entries[f]["annotation_triggers"])
        ),
        "requirements_consumers": req_consumers,
        "platforms": _platform_claims(tree_root),
        "tooling": _tooling_facts(tree_root),
        "smoke_tests": SMOKE_TESTS,
    }


