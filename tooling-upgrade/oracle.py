def annotation_triggers(tree: ast.Module | None) -> list[str]:
    found: set[str] = set()
    for node in ast.walk(tree) if tree else ():
        if isinstance(node, ast.Name) and node.id in ANNOTATION_TRIGGERS:
            found.add(ANNOTATION_TRIGGERS[node.id])
        elif isinstance(node, ast.Attribute) and node.attr in ANNOTATION_TRIGGERS:
            found.add(ANNOTATION_TRIGGERS[node.attr])
        elif isinstance(node, ast.ImportFrom) and node.module:
            top = node.module.split(".")[0]
            if top in ("pydantic", "dataclasses"):
                found.add(ANNOTATION_TRIGGERS[top])
            for a in node.names:
                if a.name in ANNOTATION_TRIGGERS:
                    found.add(ANNOTATION_TRIGGERS[a.name])
        elif isinstance(node, ast.Import):
            for a in node.names:
                if a.name.split(".")[0] in ("pydantic", "dataclasses"):
                    found.add(ANNOTATION_TRIGGERS[a.name.split(".")[0]])
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for d in node.decorator_list:
                d = d.func if isinstance(d, ast.Call) else d
                if isinstance(d, ast.Attribute) and d.attr in ("tool", "resource", "prompt"):
                    found.add(f"@*.{d.attr} decorator")
    return sorted(found)


class RepoGraph:
    """Static import graph over the tracked .py files of one tree."""

    def __init__(self, tree_root: Path, files: list[str]):
        self.root = tree_root
        self.files = [f for f in files if f.endswith(".py")]
        self.asts: dict[str, ast.Module | None] = {f: parse_file(tree_root / f) for f in self.files}
        self.by_dotted: dict[str, str] = {}
        for f in self.files:
            d = dotted_name(f)
            if d:
                self.by_dotted.setdefault(d, f)
        self.edges: dict[str, set[str]] = {f: set() for f in self.files}  # importer -> imported files
        self.ext_names: dict[str, set[str]] = {}  # file -> names others take from it
        for f in self.files:
            self._scan(f)

    def _resolve(self, importer: str, dotted: str) -> list[str]:
        hits: list[str] = []
        parts = dotted.split(".")
        for i in range(1, len(parts) + 1):
            f = self.by_dotted.get(".".join(parts[:i]))
            if f:
                hits.append(f)
        # script-local import: a sibling module next to the importer (sys.path[0] is its dir)
        base = os.path.dirname(importer)
        for cand in (dotted.replace(".", "/") + ".py", dotted.replace(".", "/") + "/__init__.py"):
            rel = (base + "/" + cand) if base else cand
            if rel in self.asts:
                hits.append(rel)
        return hits

    def _scan(self, f: str) -> None:
        tree = self.asts[f]
        if tree is None:
            return
        pkg = f[:-3].split("/")[:-1]  # the importer's package (for __init__.py: its own dir)
        aliases: dict[str, str] = {}
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for a in node.names:
                    for hit in self._resolve(f, a.name):
                        self.edges[f].add(hit)
                    if a.asname:
                        aliases[a.asname] = a.name
                    else:
                        aliases[a.name.split(".")[0]] = a.name.split(".")[0]
                        aliases[a.name] = a.name
            elif isinstance(node, ast.ImportFrom):
                if node.level:
                    base = pkg[: len(pkg) - (node.level - 1)] if node.level > 1 else pkg
                    mod = ".".join(base + ([node.module] if node.module else []))
                else:
                    mod = node.module or ""
                targets = self._resolve(f, mod) if mod else []
                for hit in targets:
                    self.edges[f].add(hit)
                for a in node.names:
                    sub = self._resolve(f, mod + "." + a.name if mod else a.name)
                    sub = [s for s in sub if s not in targets]
                    if sub:
                        self.edges[f].update(sub)
                    elif targets and a.name != "*":
                        self.ext_names.setdefault(targets[-1], set()).add(a.name)
            elif isinstance(node, ast.Call):
                fn = ast.unparse(node.func)
                if (
                    fn.endswith(("import_module", "__import__", "run_module"))
                    and node.args
                    and isinstance(node.args[0], ast.Constant)
                    and isinstance(node.args[0].value, str)
                ):
                    for hit in self._resolve(f, node.args[0].value):
                        self.edges[f].add(hit)
        for node in ast.walk(tree):
            if isinstance(node, ast.Attribute) and isinstance(node.value, (ast.Name, ast.Attribute)):
                owner = ast.unparse(node.value)
                if owner in aliases:
                    hits = self._resolve(f, aliases[owner])
                    if hits and not node.attr.startswith("_"):
                        self.ext_names.setdefault(hits[-1], set()).add(node.attr)

    def reverse(self) -> dict[str, set[str]]:
        rev: dict[str, set[str]] = {f: set() for f in self.files}
        for src, dsts in self.edges.items():
            for d in dsts:
                rev.setdefault(d, set()).add(src)
        return rev


