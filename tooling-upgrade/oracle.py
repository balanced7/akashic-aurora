def surface_o6(tree: Path, raw: Path, python: Path | str | None = None) -> dict[str, Any]:
    out: dict[str, dict[str, Any]] = {}
    for p in sorted((tree / "scripts" / "checkers").glob("*.py")):
        if p.name.startswith("_"):
            continue
        progress(f"O6 {p.stem}")
        try:
            r = run(
                [python or venv_python(tree), p.relative_to(tree).as_posix()],
                cwd=tree,
                env=oracle_env(),
                timeout=CHECKER_TIMEOUT_S,
            )
            text = normalize_text(r.stdout + r.stderr, tree)
            item: dict[str, Any] = {
                "rc": r.returncode,
                "crashed": "Traceback (most recent call last)" in text,
                "lines": len(text.splitlines()),
                "digest": sha256_bytes(text.encode()),
            }
            if r.returncode == 2 and "usage:" in text and "required" in text:
                item["na"] = "needs arguments"
            (raw / (f"O6-{p.stem}.log")).write_text(text, encoding="utf-8")
        except subprocess.TimeoutExpired:
            item = {"rc": 999, "crashed": True, "lines": 0, "digest": "", "na": "timeout"}
        out[p.stem] = item
    return {"checkers": out}


def compare_o6(a: dict[str, Any], b: dict[str, Any], partial: bool = False) -> list[tuple[str, str]]:  # noqa: FBT001, RUF100  # positional flag kept: signature probed by the oracle (O5); FBT is ratchet-only
    diffs: list[tuple[str, str]] = []
    for name, r in sorted(a["checkers"].items()):
        rb = b["checkers"].get(name)
        if rb is None:
            diffs.append(("checker:" + name, "checker gone"))
            continue
        if rb["crashed"] and not r["crashed"]:
            diffs.append(("checker:" + name, "now crashes"))
        elif rb["rc"] > r["rc"]:
            diffs.append(("checker:" + name, "exit {:d} > baseline {:d}".format(rb["rc"], r["rc"])))
    return diffs


