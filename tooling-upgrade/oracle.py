def impacted(commit: str) -> list[str]:
    changed = git("diff", "--name-only", commit + "^", commit, "--", "*.py").splitlines()
    return _impacted_tests(changed, [f for f in tracked_files() if f.endswith(".py")])


def worktree_impacted() -> list[str]:
    """The test-fast selection (G1.P6): the smoke set plus every test that imports, directly
    or transitively, a .py changed or added since HEAD (uncommitted and untracked files)."""
    changed = set(git("diff", "--name-only", "HEAD", "--", "*.py").split())
    changed |= set(git("ls-files", "--others", "--exclude-standard", "--", "*.py").split())
    changed = {c for c in changed if (ROOT / c).exists()}
    pys = sorted({f for f in tracked_files() if f.endswith(".py")} | changed)
    return _impacted_tests(sorted(changed), pys)


def _impacted_tests(changed: Iterable[str], pys: list[str]) -> list[str]:
    graph = RepoGraph(ROOT, pys)
    rev = graph.reverse()
    seen: set[str] = set()
    stack = [c for c in changed if c in graph.asts]
    while stack:
        f = stack.pop()
        if f in seen:
            continue
        seen.add(f)
        stack.extend(rev.get(f, ()))
    tests = {f for f in seen if f.startswith("tests/") and f.rsplit("/", 1)[-1].startswith("test")}
    tests |= {t for t in SMOKE_TESTS if (ROOT / t).exists()}
    return sorted(tests)


def cmd_impacted(args: argparse.Namespace) -> int:
    for t in impacted(args.commit):
        print(t)
    return 0


def cmd_test_fast(args: argparse.Namespace) -> int:
    """`poe test-fast`: the impacted selection (smoke set when nothing changed), REDIS_DB=15."""
    tests = worktree_impacted()
    progress("test-fast: {:d} test files: {}".format(len(tests), " ".join(tests)[:300]))
    r = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", *tests],
        cwd=str(ROOT),
        env=oracle_env(),
        stdin=subprocess.DEVNULL,
    )
    return r.returncode


def cmd_guardrails(args: argparse.Namespace) -> int:
    """`poe guardrails`: every scripts/checkers/* run with its documented arguments (the one that
    needs a commit message and paths, check_reconciliation_gate, is run by scripts/ship.py per
    commit and recorded N/A here), each held to its g0 exit code: O6's rule, a checker may not
    exit worse or newly crash. Many checkers were already red at g0; their repair is not G1's."""
    raw = Path(tempfile.mkdtemp(prefix="aurora-guardrails-"))
    try:
        cur = surface_o6(ROOT, raw, sys.executable)
    finally:
        _rmtree(raw)
    base = load_json(SNAPSHOTS / "g0" / "O6.json")
    if args.only:
        # one CI step per guardrail (G5.P3): the same g0 rule, held for the named checkers only
        unknown = sorted(set(args.only) - set(cur["checkers"]))
        if unknown:
            print("GUARDRAILS: FAIL (no such checker: {})".format(", ".join(unknown)))  # noqa: T201  # CLI output: the guardrails verdict line
            return 2
        cur = {"checkers": {k: v for k, v in cur["checkers"].items() if k in args.only}}
        base = {"checkers": {k: v for k, v in base["checkers"].items() if k in args.only}}
    worse = dict(compare_o6(base, cur))
    for name, r in sorted(cur["checkers"].items()):
        b = base["checkers"].get(name, {})
        verdict = "WORSE: " + worse["checker:" + name] if "checker:" + name in worse else "ok"
        print(
            "{!s:<28} exit {!s:<3} (g0 {}){}  {}".format(
                name, r["rc"], b.get("rc", "-"), " N/A: " + r["na"] if r.get("na") else "", verdict
            )
        )
    print("GUARDRAILS: %s" % ("PASS (no checker worse than g0)" if not worse else f"FAIL ({len(worse):d} worse)"))
    return 1 if worse else 0


# ----------------------------------------------------------------------------- self-tests


def _drop_function(tree: Path, inv: dict[str, Any], base_o5: dict[str, Any]) -> tuple[str, str]:
    """Pick the first core module (sorted) whose baseline surface has a public top-level def
    that exists in source, and delete that def. Returns (module, function)."""
    for mod in sorted(base_o5["modules"]):
        if not mod.startswith("core."):
            continue
        rel = next((f for f, e in inv["files"].items() if e["module"] == mod), None)
        if rel is None or rel.endswith("__init__.py"):
            continue
        src = (tree / rel).read_text(encoding="utf-8")
        t = ast.parse(src)
        for node in t.body:
            if (
                isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
                and node.name in base_o5["modules"][mod]["names"]
            ):
                start = min([node.lineno] + [d.lineno for d in node.decorator_list])
                lines = src.splitlines(keepends=True)
                del lines[start - 1 : node.end_lineno]
                (tree / rel).write_text("".join(lines), encoding="utf-8")
                return mod, node.name
    raise RuntimeError("no core module with a removable public function")


def cmd_selftest_d14(args: argparse.Namespace) -> int:
    base = snapshot_dir(args.baseline)
    base_o5 = load_json(base / "O5.json")
