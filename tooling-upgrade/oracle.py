def load_intended() -> list[dict[str, Any]]:
    """INTENDED_CHANGES.md: one ```toml block per entry (id, component, key glob, reason)."""
    if not INTENDED.exists():
        return []
    text = INTENDED.read_text(encoding="utf-8")
    out: list[dict[str, Any]] = []
    for block in re.findall(r"```toml\n(.*?)```", text, flags=re.S):
        entry = tomllib.loads(block)
        if {"id", "component", "key", "reason"} <= set(entry):
            out.append(entry)
    return out


def compare_dirs(
    a: Path,
    b: Path,
    components: Sequence[str] | None = None,
    partial: bool = False,  # noqa: FBT001, RUF100  # positional flag kept: signature probed by the oracle (O5); FBT is ratchet-only
    intended: list[dict[str, Any]] | None = None,
) -> tuple[list[str], bool]:
    intended = load_intended() if intended is None else intended
    lines: list[str] = []
    equal = 0
    comps = components or list(COMPONENTS)
    for c in comps:
        if c == "O2":
            ma: dict[str, Any] = load_json(a / "meta.json") if (a / "meta.json").exists() else {}
            mb: dict[str, Any] = load_json(b / "meta.json") if (b / "meta.json").exists() else {}
            commits = format_commits(ma.get("commit"), mb.get("commit"))
            bad: list[str] = []
            for sha in commits:
                bad += [p for p, ok, _ in ast_equal(sha + "^", sha) if not ok]
            if bad:
                lines.append("O2 DIFF {:d} {}".format(len(bad), ", ".join(bad[:5])))
            else:
                equal += 1
                lines.append(f"O2 EQUAL ({len(commits):d} format commits)")
            continue
        fa, fb = a / (c + ".json"), b / (c + ".json")
        if not fa.exists() or not fb.exists():
            lines.append(f"{c} MISSING ({fa if not fa.exists() else fb})")
            continue
        diffs = COMPARATORS[c](load_json(fa), load_json(fb), partial)
        covered = [
            d for d in diffs if any(e["component"] == c and fnmatch.fnmatchcase(d[0], e["key"]) for e in intended)
        ]
        open_ = [d for d in diffs if d not in covered]
        if not open_:
            equal += 1
            ids = sorted(
                {
                    e["id"]
                    for d in covered
                    for e in intended
                    if e["component"] == c and fnmatch.fnmatchcase(d[0], e["key"])
                }
            )
            lines.append("{} EQUAL{}".format(c, " (intended: {})".format(", ".join(ids)) if ids else ""))
        else:
            summary = "; ".join("{}: {}".format(*d) for d in open_[:3])
            lines.append(f"{c} DIFF {len(open_):d} {summary}")
    lines.append(f"ORACLE: {equal:d}/{len(comps):d} EQUAL")
    return lines, equal == len(comps)


def snapshot_dir(label: str) -> Path:
    return SNAPSHOTS / ("head" if label == "HEAD" else label)


def cmd_snapshot(args: argparse.Namespace) -> int:
    comps = args.components.split(",") if args.components else None
    mods = set(args.modules.split(",")) if args.modules else None
    sel = tuple(args.select.split(",")) if args.select else ()
    dest = snapshot(args.label, args.ref, args.runs, args.reruns, comps, mods, select=sel, python=args.python)
    print(f"snapshot written: {dest.relative_to(ROOT)}")
    return 0


def cmd_compare(args: argparse.Namespace) -> int:
    comps = args.components.split(",") if args.components else None
    lines, ok = compare_dirs(snapshot_dir(args.a), snapshot_dir(args.b), comps, args.partial)
    print("\n".join(lines))
    return 0 if ok else 1


def verify_snapshot(label: str, suite_runs: int) -> list[str]:
    d = snapshot_dir(label)
    problems: list[str] = []
    if not (d / "meta.json").exists():
        return [f"no meta.json in {d}"]
    meta = load_json(d / "meta.json")
    for c in COMPONENTS:
        p = d / (c + ".json")
        if not p.exists():
            problems.append(f"{c} missing")
            continue
        m = load_json(p).get("_meta", {})
        if m.get("digest") != meta["digest"]:
            problems.append(f"{c} taken at a different tree than meta.json")
        if m.get("partial_modules"):
            problems.append(f"{c} is a partial (module-restricted) capture")
        if m.get("dirty"):
            problems.append(f"{c} taken in a dirty tree")
        if m.get("select"):
            problems.append(f"{c} ran a test SELECTION, not the full suite")
    if (d / "O1.json").exists() and len(load_json(d / "O1.json")["runs"]) < suite_runs:
        problems.append(f"O1 has fewer than {suite_runs:d} suite runs")
    if not meta.get("raw_digests"):
        problems.append("meta.json has no raw-log digests")
    return problems


def cmd_verify_snapshot(args: argparse.Namespace) -> int:
    problems = verify_snapshot(args.label, args.suite_runs)
    for p in problems:
        print("  ", p)
    print("SNAPSHOT {}: {}".format(args.label, "COMPLETE" if not problems else "INCOMPLETE"))
    return 1 if problems else 0


